export const DIRECTED_TYPES = EVENT_TYPE_IDS.filter(id => EVENT_TYPES[id].directed);

/** 空值与未知类别的兜底标签 */
export const NEUTRAL_TYPE = 'neutral';

/**
 * 查询某个类别被否定后应落到哪个类别。
 * 返回 null 表示该类别没有显式对偶，由调用方按影响向量取反处理。
 * @param {string} type
 * @returns {string|null}
 */
export function getNegatedType(type) {
  const def = EVENT_TYPES[type];
  if (!def) return null;
  return def.negatedAs || null;
}

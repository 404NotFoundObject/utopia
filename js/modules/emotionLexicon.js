// js/modules/emotionLexicon.js - 情绪识别的词汇与结构词表（纯数据，零依赖）
//
// 设计说明：
//   1. 词表分「强词」words（权重 2）与「弱词」weakWords（权重 1）。
//      弱词只在「同类别」于同一子句内已有强词命中时才计入，
//      用于收纳「去」「做」「能」这类单独出现极易误判的高频字。
//   2. 每个类别声明 polarity，供正负极性冲突检测使用。
//   3. negatedAs 声明该类别被否定后映射到哪个类别；为 null 时
//      由分类器统一按「影响向量取反」处理。
//   4. directed 标记该事件的情感是否「指向某个人」，只有 directed 类别
//      才需要校验施事与受体，用于识别第三方介入。
//   5. patterns 只保留「指向性足够强」的写法。
//      正则匹配拿不到可靠的否定位置，因此宽泛的模式（如「太(.*?)了」
//      「你真(.*?)」「其实(.*?)」）一律不收 —— 它们会在「太累了」
//      「你真棒」「其实我喜欢你」上错误加分，是误判的主要来源。
//   6. prototypes 是语义层的原型句，刻意保持「极性干净」：不含否定式。
//      否定由规则层硬处理，语义层不得参与。

